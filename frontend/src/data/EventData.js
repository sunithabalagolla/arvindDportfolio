// Helper function to get event by ID
export const getEventById = (id) => {
    return eventsData.find(event => event.id === parseInt(id));
};

// Helper function to get related events (same tags, excluding current)
export const getRelatedEvents = (currentEventId, limit = 3) => {
    const currentEvent = getEventById(currentEventId);
    if (!currentEvent) return [];
    
    return eventsData
        .filter(event => 
            event.id !== currentEventId && 
            event.tags.some(tag => currentEvent.tags.includes(tag))
        )
        .slice(0, limit);
};

